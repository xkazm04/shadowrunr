// The contract generator: JSON Schema (exported from crates/shadowrunr-types) -> TS types,
// compiled ajv validators and the method/error metadata. Used by generate.mjs and check.mjs.
// Output is deterministic: the same schema always yields byte-identical files.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

export const SCHEMA_FILE = "contract.schema.json";
export const GENERATED_FILES = ["types.ts", "validators.js", "validators.d.ts", "meta.ts"];
const MAX_ERROR_CODES = 10;

const BANNER = [
  "// GENERATED by packages/contract/scripts/generate.mjs from crates/shadowrunr-types.",
  "// Do not edit: change the Rust types, then run `pnpm -C packages/contract generate`.",
].join("\n");

const lf = (text) => text.replace(/\r\n/g, "\n");

/** The `$defs` name a method's result refers to. */
function resultDef(schema, method) {
  const ref = schema.properties[method].properties.result.$ref;
  if (typeof ref !== "string" || !ref.startsWith("#/$defs/")) {
    throw new Error(`schema: ${method}.result must be a $ref into $defs`);
  }
  return ref.slice("#/$defs/".length);
}

const SHAPE_KEYS = ["type", "$ref", "properties", "items", "anyOf", "oneOf", "allOf", "enum", "const"];
const map = (obj, f) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, f(v)]));

/** Prepare a schema for json-schema-to-typescript (the schema file itself is untouched):
 * - `{$ref, description, default}` would declare a duplicate type (`Usage1`), so a reference
 *   is the reference alone;
 * - an any-schema (`serde_json::Value`) is `unknown`, not an index-signature object;
 * - 2020-12 tuples (`prefixItems`) become draft-07 tuples (`items: [...]`). */
function forTs(schema) {
  if (schema === null || typeof schema !== "object") return schema;
  if (typeof schema.$ref === "string") return { $ref: schema.$ref };
  const out = { ...schema };
  if (!SHAPE_KEYS.some((k) => k in out) && !("prefixItems" in out)) out.tsType = "unknown";
  for (const k of ["properties", "$defs"]) if (out[k]) out[k] = map(out[k], forTs);
  for (const k of ["items", "additionalProperties"]) if (typeof out[k] === "object") out[k] = forTs(out[k]);
  for (const k of ["anyOf", "oneOf", "allOf"]) if (out[k]) out[k] = out[k].map(forTs);
  if (out.prefixItems) {
    out.items = out.prefixItems.map(forTs);
    delete out.prefixItems;
  }
  return out;
}

async function typesTs(schema) {
  const ts = await compile(forTs(schema), "RpcMethods", {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    unknownAny: true,
    declareExternallyReferenced: true,
    format: true,
    customName: (_schema, keyNameFromDefinition) => keyNameFromDefinition,
  });
  return lf(ts);
}

function validatorFiles(schema, methods) {
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    inlineRefs: false,
    strict: true,
    allowUnionTypes: true,
    validateFormats: false,
  });
  ajv.addSchema(schema);
  const ref = (name) => `${schema.$id}#/$defs/${name}`;
  // One validator per def: methods sharing a result type share its validator.
  const defs = [
    ...new Set(["ServerFrame", "ErrorEnvelope", ...methods.map((m) => resultDef(schema, m))]),
  ];
  const exported = Object.fromEntries(defs.map((d) => [`validate${d}`, ref(d)]));
  const js = ["// @ts-nocheck", "/* eslint-disable */", BANNER, standaloneCode(ajv, exported), ""];
  const dts = [
    BANNER,
    `import type { ErrorObject } from "ajv";`,
    `import type * as T from "./types";`,
    ``,
    `/** A compiled validator: a type guard that leaves its errors on \`.errors\`. */`,
    `export interface ValidateFn<V> {`,
    `  (data: unknown): data is V;`,
    `  errors?: ErrorObject[] | null;`,
    `}`,
    ``,
    ...defs.map((d) => `export declare const validate${d}: ValidateFn<T.${d}>;`),
    ``,
  ];
  return { js: lf(js.join("\n")), dts: dts.join("\n") };
}

function errorCodes(schema) {
  const def = schema.$defs.ErrorCode;
  const codes = def.enum ?? def.oneOf.map((v) => v.const);
  if (codes.length > MAX_ERROR_CODES) {
    throw new Error(`schema: the error taxonomy holds at most ${MAX_ERROR_CODES} codes`);
  }
  return codes;
}

function metaTs(schema, methods) {
  const lines = [
    BANNER,
    `import type { RpcMethods } from "./types";`,
    `import type { ValidateFn } from "./validators.js";`,
    `import * as v from "./validators.js";`,
    ``,
    `/** Every RPC method, sorted. */`,
    `export const RPC_METHODS = [`,
    ...methods.map((m) => `  ${JSON.stringify(m)},`),
    `] as const;`,
    ``,
    `export type RpcMethod = keyof RpcMethods;`,
    `export type RpcParams<M extends RpcMethod> = RpcMethods[M]["params"];`,
    `export type RpcResult<M extends RpcMethod> = RpcMethods[M]["result"];`,
    ``,
    `/** The error taxonomy (at most ten codes). */`,
    `export const ERROR_CODES = [`,
    ...errorCodes(schema).map((c) => `  ${JSON.stringify(c)},`),
    `] as const;`,
    ``,
    `/** The result validator of every method. */`,
    `export const RESULT_VALIDATORS: { readonly [M in RpcMethod]: ValidateFn<RpcResult<M>> } = {`,
    ...methods.map((m) => `  ${JSON.stringify(m)}: v.validate${resultDef(schema, m)},`),
    `};`,
    ``,
  ];
  return lines.join("\n");
}

/** Generate every file from `<schemaDir>/contract.schema.json` into `outDir`. */
export async function generate(schemaDir, outDir) {
  const schema = JSON.parse(await readFile(join(schemaDir, SCHEMA_FILE), "utf8"));
  const methods = Object.keys(schema.properties);
  if ([...methods].sort().join() !== [...schema.required].sort().join()) {
    throw new Error("schema: every method must be required");
  }
  const { js, dts } = validatorFiles(schema, methods);
  const files = {
    "types.ts": await typesTs(schema),
    "validators.js": js,
    "validators.d.ts": dts,
    "meta.ts": metaTs(schema, methods),
  };
  await mkdir(outDir, { recursive: true });
  for (const name of GENERATED_FILES) await writeFile(join(outDir, name), files[name]);
  return GENERATED_FILES;
}
